  brandMark: { width: 38, height: 38, alignItems: "center", justifyContent: "center", borderRadius: 8, backgroundColor: "#0B1F3A", marginRight: 10 },
  brand: { fontSize: 20, fontWeight: 700, color: "#0B1F3A" },
  headerMeta: { alignItems: "flex-end" },
  receiptTitle: { fontSize: 9, color: "#5B6478" },
  statusBadge: { marginTop: 7, paddingVertical: 5, paddingHorizontal: 9, borderRadius: 10 },
  status: { fontSize: 9, fontWeight: 700 },
  amountBox: { alignItems: "center", marginVertical: 24, padding: 22, borderRadius: 10, backgroundColor: "#F5F1E8" },
  amountLabel: { fontSize: 9, color: "#5B6478", marginBottom: 4 },
  amount: { fontSize: 28, fontWeight: 700, color: "#0B1F3A" },
  row: { flexDirection: "row", justifyContent: "space-between", paddingVertical: 8, borderBottom: 1, borderBottomColor: "#DCD4BF" },
